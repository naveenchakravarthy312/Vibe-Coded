export function serializeAppsJson(apps: AppCatalogItem[]): string {
  const clean = apps.map(({ id, name, category, method, wingetId, portableUrl, portableFolder, description, arm64Safe, version }) => ({
    id,
    name,
    category,
    method,
    ...(wingetId ? { winget_id: wingetId } : {}),
    ...(portableUrl ? { portable_url: portableUrl } : {}),
    ...(portableFolder ? { portable_folder: portableFolder } : {}),
    description,
    arm64_safe: arm64Safe,
    ...(version ? { version } : {}),
  }));
  return JSON.stringify({ schema_version: 1, apps: clean }, null, 2);
}
